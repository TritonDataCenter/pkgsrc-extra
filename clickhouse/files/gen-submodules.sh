#!/bin/sh
#
# Generate submodules.mk from a ClickHouse checkout: one distfile per
# submodule, fetched from its original repository at the pinned commit.
#
# Usage: gen-submodules.sh /path/to/ClickHouse [rev] > submodules.mk

set -eu

repo=$1
rev=${2:-HEAD}

printf '# $NetBSD$\n#\n'
printf '# Generated by files/gen-submodules.sh from ClickHouse %s.\n' \
	"$(git -C "$repo" rev-parse "$rev")"
printf '# Do not edit manually.\n#\n'
printf '# SM+=	<contrib path> <github org> <repository> <commit>\n\n'

git -C "$repo" config -f "$repo/.gitmodules" \
    --get-regexp '^submodule\..*\.path$' |
while read -r key path; do
	name=${key#submodule.}
	name=${name%.path}
	url=$(git -C "$repo" config -f "$repo/.gitmodules" \
	    --get "submodule.$name.url")
	sha=$(git -C "$repo" ls-tree "$rev" -- "$path" | awk '{print $3}')
	if [ -z "$sha" ]; then
		echo "WARNING: $path has no gitlink in $rev, skipped" >&2
		continue
	fi
	base=${url%.git}
	reponame=${base##*/}
	org=${base%/*}
	org=${org##*/}
	printf 'SM+=\t%s %s %s %s\n' "$path" "$org" "$reponame" "$sha"
done

cat <<'EOF'

GH=		https://github.com
.for sm_path sm_org sm_repo sm_sha in ${SM}
DISTFILES+=	${sm_repo}-${sm_sha}.tar.gz
SITES.${sm_repo}-${sm_sha}.tar.gz=	-${GH}/${sm_org}/${sm_repo}/archive/${sm_sha}.tar.gz
SUBMODULES+=	${sm_path} ${sm_repo}-${sm_sha}
.endfor
EOF
